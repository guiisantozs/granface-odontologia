import { test, expect } from '@playwright/test';

test('desktop: a experiência completa funciona sem envio ou persistência', async ({ page, baseURL }) => {
  const errors: string[] = [];
  const outgoing: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (!request.url().startsWith(new URL(baseURL!).origin) && !request.url().startsWith('data:') && !request.url().startsWith('blob:')) outgoing.push(request.url()) });
  await page.goto('./');
  await expect(page.getByRole('heading', {name:'Mais do que sorrisos.'})).toBeVisible();
  await expect(page.locator('.hero-model canvas')).toBeVisible();
  await page.waitForTimeout(4000);
  await page.screenshot({path:'test-results/desktop-hero.png'});
  for (const id of ['sobre','tratamentos','especialistas','simulador','resultados','agendamento']) await expect(page.locator(`#${id}`)).toBeAttached();
  await page.locator('#tratamentos').scrollIntoViewIfNeeded();
  await page.waitForTimeout(1200);
  const cards=page.locator('.treatment-card');
  await cards.nth(2).hover();
  await expect(cards.nth(2)).toHaveClass(/is-active/);
  await page.waitForTimeout(850);
  expect((await cards.nth(2).boundingBox())!.width).toBeGreaterThan((await cards.nth(1).boundingBox())!.width*1.6);
  await page.screenshot({path:'test-results/desktop-treatments.png'});
  await page.locator('#especialistas').scrollIntoViewIfNeeded();
  await page.getByRole('button',{name:'Próximo especialista',exact:true}).click();
  await expect.poll(()=>page.locator('.specialist-slider').evaluate(el=>el.scrollLeft)).toBeGreaterThan(100);
  await page.locator('#simulador').scrollIntoViewIfNeeded();
  await page.getByRole('button',{name:'Alinhar meus dentes'}).click();
  await expect(page.locator('.sim-result h3')).toHaveText('Ortodontia');
  await page.getByRole('button',{name:'Natural',exact:true}).click();
  await expect(page.getByRole('button',{name:'Natural',exact:true})).toHaveClass(/selected/);
  await page.getByRole('button',{name:'Lateral',exact:true}).click();
  await expect(page.getByRole('button',{name:'Lateral',exact:true})).toHaveClass(/selected/);
  await page.getByRole('button',{name:'Pausar rotação',exact:true}).click();
  await expect(page.getByRole('button',{name:'Retomar rotação',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Recomeçar experiência'}).click();
  await expect(page.locator('.sim-result h3')).toHaveText('Estética Dental');
  await page.waitForTimeout(1500);
  await page.screenshot({path:'test-results/desktop-simulator.png'});
  const canvas=page.locator('.sim-viewport canvas');
  const box=(await canvas.boundingBox())!;
  const initialTooth=await page.locator('.model-tag').innerText();
  await canvas.click({position:{x:box.width*.65,y:box.height*.31}});
  await expect(page.locator('.model-tag')).not.toHaveText(initialTooth);
  await page.mouse.move(box.x+box.width/2,box.y+box.height/2);
  await page.mouse.down();await page.mouse.move(box.x+box.width/2+70,box.y+box.height/2+25,{steps:8});await page.mouse.up();
  await page.locator('#resultados').scrollIntoViewIfNeeded();
  await page.getByRole('tab',{name:'Clareamento Dental'}).click();
  await expect(page.getByRole('tab',{name:'Clareamento Dental'})).toHaveAttribute('aria-selected','true');
  const range=page.getByRole('slider',{name:'Comparador visual de antes e depois'});
  await range.focus();await range.press('Home');await expect(range).toHaveValue('2');
  await range.press('End');await expect(range).toHaveValue('98');
  await range.scrollIntoViewIfNeeded();
  await range.hover();
  const r=(await range.boundingBox())!;
  await page.mouse.move(r.x+r.width*.5,r.y+r.height*.5);await page.mouse.down();await page.mouse.move(r.x+r.width*.25,r.y+r.height*.5,{steps:10});await page.mouse.up();
  expect(Number(await range.inputValue())).toBeLessThan(40);
  await page.screenshot({path:'test-results/desktop-results.png'});
  await page.getByRole('button',{name:'Próximo exemplo',exact:true}).click();
  await page.locator('#agendamento').scrollIntoViewIfNeeded();
  await page.getByRole('textbox',{name:'Como podemos chamar você?'}).fill('Apresentação Granface');
  await page.getByRole('textbox',{name:'Seu telefone'}).fill('11999999999');
  await page.getByRole('combobox',{name:'O que você procura?'}).selectOption({label:'Estética Dental'});
  await page.getByLabel('Data desejada').fill('2027-01-20');
  await page.getByRole('button',{name:'Confirmar avaliação',exact:true}).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  const modal=(await page.getByRole('dialog').boundingBox())!;
  expect(Math.abs(modal.x+modal.width/2-720)).toBeLessThan(3);
  await expect(page.getByText('Esta é uma demonstração visual do futuro site da Granface.',{exact:true})).toBeVisible();
  await page.screenshot({path:'test-results/desktop-modal.png'});
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  expect(await page.evaluate(()=>({local:localStorage.length,session:sessionStorage.length}))).toEqual({local:0,session:0});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  expect(await page.locator('img').evaluateAll(images=>images.every(img=>img.complete&&img.naturalWidth>0))).toBe(true);
  expect(errors).toEqual([]);
  expect(outgoing).toEqual([]);
});

test.describe('Interação por toque',()=>{
test.use({hasTouch:true,isMobile:true});
test('mobile: menu, cards por toque, comparador e layout', async ({ page })=>{
  await page.setViewportSize({width:390,height:844});
  await page.goto('./');await page.waitForTimeout(3000);
  await page.screenshot({path:'test-results/mobile-hero.png'});
  await page.getByRole('button',{name:'Abrir menu',exact:true}).click();
  await expect(page.getByRole('navigation')).toBeVisible();
  await page.getByRole('navigation').getByRole('link',{name:'Tratamentos',exact:true}).click();
  await expect(page.getByRole('navigation')).toBeHidden();
  const cards=page.locator('.treatment-card');
  await cards.nth(3).click();
  await expect(cards.nth(3)).toHaveClass(/is-active/);
  await page.waitForTimeout(800);
  expect((await cards.nth(3).boundingBox())!.height).toBeGreaterThan(200);
  await page.locator('#simulador').scrollIntoViewIfNeeded();
  await page.getByRole('button',{name:'Reabilitar meu sorriso'}).click();
  await expect(page.locator('.sim-result h3')).toHaveText('Implantodontia');
  await page.locator('#resultados').scrollIntoViewIfNeeded();
  const touchRange=page.getByRole('slider');
  await touchRange.scrollIntoViewIfNeeded();
  await touchRange.tap({position:{x:80,y:100}});
  expect(Number(await touchRange.inputValue())).toBeLessThan(40);
  await page.getByRole('slider').fill('72');
  await expect(page.locator('.compare-handle')).toHaveAttribute('style','left: 72%;');
  for(const id of ['inicio','sobre','tratamentos','especialistas','simulador','resultados','agendamento']){
    await page.locator(`#${id}`).scrollIntoViewIfNeeded();
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),id).toBe(true);
  }
  await expect(page.locator('.booking-form')).toHaveCSS('opacity','1');
  await page.screenshot({path:'test-results/mobile-booking.png'});
});
});
